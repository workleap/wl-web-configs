import { defineConfig } from "oxfmt";

export default defineConfig({
    // oxfmt also honors .gitignore (dist, storybook-static, ...) and would honor a .prettierignore.
    // - .agents/ holds vendored skills (skills-lock.json): upstream replaces them wholesale.
    // - .claude/ holds local skill prose (reflowing it is churn) and, in a main checkout, the agent worktrees.
    // - agent-skills/ and packages/*/skills/ are loaded into agents' context: padded Markdown tables triple
    //   their size. The sync-agent-skill workflow also edits them without running oxfmt.
    // - docs/ is Retype markdown, whose components (!!!, +++, [!ref]) a Markdown formatter can mangle.
    // - CHANGELOG.md files are generated by Changesets.
    ignorePatterns: [
        ".agents/",
        ".claude/",
        "agent-skills/",
        "packages/*/skills/",
        "docs/",
        "skills-lock.json",
        "pnpm-lock.yaml",
        "**/CHANGELOG.md",
        "**/mockServiceWorker.js"
    ],
    printWidth: 150,
    tabWidth: 4,
    useTabs: false,
    singleQuote: false,
    jsxSingleQuote: false,
    semi: true,
    trailingComma: "none",
    arrowParens: "avoid",
    bracketSpacing: true,
    bracketSameLine: false,
    quoteProps: "as-needed",
    endOfLine: "lf",
    sortPackageJson: {
        sortScripts: false
    },
    overrides: [
        {
            // The YAML files (GitHub workflows, pnpm-workspace.yaml) are indented with 2 spaces.
            files: ["**/*.yml", "**/*.yaml"],
            options: { tabWidth: 2 }
        },
        {
            // Code fences often show consumers' files, such as 2-space GitHub workflows: format the prose only.
            files: ["**/*.md"],
            options: { embeddedLanguageFormatting: "off" }
        }
    ]
});
